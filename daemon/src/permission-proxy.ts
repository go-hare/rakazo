const TEAM_TOOLS = new Set(["list_fleet", "message_bot", "handoff_to_bot"]);

const send = (value: unknown) => process.stdout.write(`${JSON.stringify(value)}\n`);

async function handle(message: Record<string, unknown>): Promise<void> {
  if (message.method === "initialize") {
    send({
      jsonrpc: "2.0",
      id: message.id,
      result: {
        protocolVersion: "2024-11-05",
        capabilities: { tools: {} },
        serverInfo: { name: "openmausbot-permissions", version: "1" },
      },
    });
    return;
  }
  if (message.method === "tools/list") {
    send({ jsonrpc: "2.0", id: message.id, result: { tools: TOOLS } });
    return;
  }
  if (message.method === "tools/call") {
    const params = message.params as
      | { name?: string; arguments?: Record<string, unknown> }
      | undefined;
    const args = params?.arguments ?? {};
    if (params?.name && TEAM_TOOLS.has(params.name)) {
      const answer = await askBroker({
        t: "team",
        id: randomUUID(),
        tool: params.name,
        input: args,
      });
      send({
        jsonrpc: "2.0",
        id: message.id,
        result: {
          content: [{ type: "text", text: answer.message || "Team action failed" }],
          ...(answer.behavior === "deny" ? { isError: true } : {}),
        },
      });
      return;
    }
    if (params?.name === "present") {
      const answer = await askBroker({
        t: "present",
        id: randomUUID(),
        presentation: args.presentation,
      });
      send({
        jsonrpc: "2.0",
        id: message.id,
        result: {
          content: [{ type: "text", text: answer.message || "Presentation failed" }],
          ...(answer.behavior === "deny" ? { isError: true } : {}),
        },
      });
      return;
    }
    if (params?.name !== "approve" && params?.name !== "ask_user") {
      send({ jsonrpc: "2.0", id: message.id, error: { code: -32602, message: "Unknown tool" } });
      return;
    }
    const nativeQuestion = params?.name === "approve" && args.tool_name === "AskUserQuestion";
    if (nativeQuestion) {
      const input = args.input as
        | { questions?: Array<{ question?: unknown; options?: Array<{ label?: unknown }> }> }
        | undefined;
      const answers: Record<string, string> = {};
      if (!Array.isArray(input?.questions) || !input.questions.length) {
        send({
          jsonrpc: "2.0",
          id: message.id,
          result: {
            content: [
              {
                type: "text",
                text: JSON.stringify({ behavior: "deny", message: "Invalid questions" }),
              },
            ],
          },
        });
        return;
      }
      for (const item of input.questions) {
        if (typeof item.question !== "string" || !item.question.trim()) continue;
        const answer = await askBroker({
          t: "ask",
          id: randomUUID(),
          kind: "question",
          tool: "ask_user",
          input: {
            question: item.question,
            choices: item.options
              ?.map((option) => option.label)
              .filter((label) => typeof label === "string"),
          },
        });
        if (answer.behavior !== "answer" || !answer.message) {
          send({
            jsonrpc: "2.0",
            id: message.id,
            result: {
              content: [
                {
                  type: "text",
                  text: JSON.stringify({ behavior: "deny", message: answer.message || "没有回答" }),
                },
              ],
            },
          });
          return;
        }
        answers[item.question] = answer.message;
      }
      send({
        jsonrpc: "2.0",
        id: message.id,
        result: {
          content: [
            {
              type: "text",
              text: JSON.stringify({ behavior: "allow", updatedInput: { ...input, answers } }),
            },
          ],
        },
      });
      return;
    }
    const question = params?.name === "ask_user";
    const answer = await askBroker({
      t: "ask",
      id: randomUUID(),
      kind: question ? "question" : "permission",
      tool: question ? "ask_user" : args.tool_name,
      input: question
        ? (args.input ?? { question: args.question, choices: args.choices })
        : args.input,
    });
    const suggestions = Array.isArray(args.permission_suggestions)
      ? args.permission_suggestions
      : undefined;
    const allowed: { behavior: "allow"; updatedInput: unknown; updatedPermissions?: unknown[] } = {
      behavior: "allow",
      updatedInput: args.input ?? {},
    };
    if (answer.always && suggestions) allowed.updatedPermissions = suggestions;
    const text = question
      ? answer.message || "没有回答"
      : JSON.stringify(
          answer.behavior === "allow"
            ? allowed
            : { behavior: "deny", message: answer.message || "拒绝了" },
        );
    send({
      jsonrpc: "2.0",
      id: message.id,
      result: {
        content: [{ type: "text", text }],
        ...(question && answer.behavior === "deny" ? { isError: true } : {}),
      },
    });
    return;
  }
  if (typeof message.method === "string" && message.method.startsWith("notifications/")) return;
  if (message.id !== undefined)
    send({ jsonrpc: "2.0", id: message.id, error: { code: -32601, message: "method not found" } });
}

let buffer = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  buffer += chunk;
  let newline = buffer.indexOf("\n");
  while (newline >= 0) {
    const line = buffer.slice(0, newline).trim();
    buffer = buffer.slice(newline + 1);
    newline = buffer.indexOf("\n");
    if (!line) continue;
    try {
      void handle(JSON.parse(line) as Record<string, unknown>);
    } catch {
      // 坏行丢掉。
    }
  }
});
process.stdin.on("end", () => process.exit(0));
